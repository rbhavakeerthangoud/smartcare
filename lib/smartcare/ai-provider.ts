/**
 * SmartCare AI Provider Interface
 * Provider-independent server-side interface for LLM integrations.
 * Supports Google Gemini, OpenAI, or any compatible provider via server-side environment variables.
 * Never exposes credentials to client-side code.
 */

export interface AIProviderMessage {
  role: "system" | "user" | "assistant";
  content: string;
}

export interface AICompletionOptions {
  temperature?: number;
  maxTokens?: number;
}

export interface AIProvider {
  readonly name: string;
  generateResponse(
    messages: AIProviderMessage[],
    options?: AICompletionOptions,
  ): Promise<string>;
}

export class AIConfigurationError extends Error {
  public readonly code = "AI_PROVIDER_NOT_CONFIGURED";
  public readonly supportedProviders = ["GEMINI", "OPENAI"];
  public readonly requiredEnvVars = ["GEMINI_API_KEY", "OPENAI_API_KEY"];

  constructor(message?: string) {
    super(
      message ||
        "No AI provider is currently configured. Please configure GEMINI_API_KEY or OPENAI_API_KEY in your server environment variables.",
    );
    this.name = "AIConfigurationError";
  }
}

/**
 * Google Gemini Provider implementation using standard HTTPS fetch.
 * Uses GEMINI_API_KEY server-side environment variable.
 */
export class GeminiProvider implements AIProvider {
  public readonly name = "Google Gemini";
  private apiKey: string;
  private model: string;

  constructor(apiKey: string, model: string = "gemini-flash-latest") {
    this.apiKey = apiKey;
    this.model = model;
  }

  async generateResponse(
    messages: AIProviderMessage[],
    options?: AICompletionOptions,
  ): Promise<string> {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(
      this.model,
    )}:generateContent`;

    // Convert messages to Gemini contents structure
    const systemInstruction = messages
      .filter((m) => m.role === "system")
      .map((m) => m.content)
      .join("\n\n");

    const contents = messages
      .filter((m) => m.role !== "system")
      .map((m) => ({
        role: m.role === "assistant" ? "model" : "user",
        parts: [{ text: m.content }],
      }));

    const payload: Record<string, unknown> = {
      contents,
      generationConfig: {
        temperature: options?.temperature ?? 0.2,
        maxOutputTokens: options?.maxTokens ?? 1024,
      },
    };

    if (systemInstruction) {
      payload.systemInstruction = {
        parts: [{ text: systemInstruction }],
      };
    }

    const response = await fetch(url, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "x-goog-api-key": this.apiKey,
      },
      body: JSON.stringify(payload),
      signal: AbortSignal.timeout(30_000),
    });

    if (!response.ok) {
      const errorText = await response.text();
      const sanitized = errorText.length > 200 ? `${errorText.slice(0, 200)}...` : errorText;
      throw new Error(`Gemini API error (${response.status}): ${sanitized}`);
    }

    const data = await response.json();
    const candidate = data?.candidates?.[0];
    const textPart = candidate?.content?.parts?.[0]?.text;

    if (!textPart) {
      throw new Error("No text response generated by Gemini provider.");
    }

    return textPart.trim();
  }
}

/**
 * OpenAI Provider implementation using standard HTTPS fetch.
 * Uses OPENAI_API_KEY server-side environment variable.
 */
export class OpenAIProvider implements AIProvider {
  public readonly name = "OpenAI";
  private apiKey: string;
  private model: string;

  constructor(apiKey: string, model: string = "gpt-4o-mini") {
    this.apiKey = apiKey;
    this.model = model;
  }

  async generateResponse(
    messages: AIProviderMessage[],
    options?: AICompletionOptions,
  ): Promise<string> {
    const url = "https://api.openai.com/v1/chat/completions";

    const payload = {
      model: this.model,
      messages: messages.map((m) => ({
        role: m.role,
        content: m.content,
      })),
      temperature: options?.temperature ?? 0.2,
      max_tokens: options?.maxTokens ?? 1024,
    };

    const response = await fetch(url, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${this.apiKey}`,
      },
      body: JSON.stringify(payload),
      signal: AbortSignal.timeout(30_000),
    });

    if (!response.ok) {
      const errorText = await response.text();
      const sanitized = errorText.length > 200 ? `${errorText.slice(0, 200)}...` : errorText;
      throw new Error(`OpenAI API error (${response.status}): ${sanitized}`);
    }

    const data = await response.json();
    const choice = data?.choices?.[0];
    const text = choice?.message?.content;

    if (!text) {
      throw new Error("No text response generated by OpenAI provider.");
    }

    return text.trim();
  }
}

/**
 * Resolves the active AI provider based exclusively on server-side environment variables.
 * Never falls back to mock responses or hardcoded keys.
 */
export function getActiveAIProvider(): AIProvider {
  const geminiKey = process.env.GEMINI_API_KEY;
  if (geminiKey && geminiKey.trim()) {
    return new GeminiProvider(geminiKey.trim());
  }

  const openAiKey = process.env.OPENAI_API_KEY;
  if (openAiKey && openAiKey.trim()) {
    return new OpenAIProvider(openAiKey.trim());
  }

  throw new AIConfigurationError();
}

/**
 * Inspects whether any supported AI provider is configured in environment variables.
 */
export function getAIProviderStatus(): {
  configured: boolean;
  providerName: string | null;
  requiredEnvVars: string[];
} {
  if (process.env.GEMINI_API_KEY?.trim()) {
    return {
      configured: true,
      providerName: "Google Gemini (GEMINI_API_KEY)",
      requiredEnvVars: ["GEMINI_API_KEY"],
    };
  }

  if (process.env.OPENAI_API_KEY?.trim()) {
    return {
      configured: true,
      providerName: "OpenAI (OPENAI_API_KEY)",
      requiredEnvVars: ["OPENAI_API_KEY"],
    };
  }

  return {
    configured: false,
    providerName: null,
    requiredEnvVars: ["GEMINI_API_KEY", "OPENAI_API_KEY"],
  };
}
